/**
 * Generated navigation files: `<root>/catalog.md` and `<root>/<domain>/_outline.md`.
 *
 * Both are derived from the index's per-file metadata (no page is re-read), are
 * rebuilt whole (never appended — v1's appended llms.txt raced under parallel
 * agents), and are written via temp file + rename so no reader sees a partial file.
 *
 * Formats are chosen to be cheap for an LLM to scan: one line per item, the path
 * first (it is what the reader acts on), no tables (pipes and padding cost tokens).
 */

import { writeFileSync, renameSync, readFileSync, mkdirSync, unlinkSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';

/** Write only if the content changed (avoids mtime churn and needless git diffs). */
export function writeAtomic(file, content) {
  try { if (readFileSync(file, 'utf-8') === content) return false; } catch { /* new file */ }
  mkdirSync(dirname(file), { recursive: true });
  const tmp = `${file}.${process.pid}.${Math.random().toString(36).slice(2)}.tmp`;
  try {
    writeFileSync(tmp, content);
    renameSync(tmp, file);
  } catch (e) {
    try { unlinkSync(tmp); } catch { /* nothing to clean */ }
    throw e;
  }
  return true;
}

const clip = (s, n) => (s && s.length > n ? s.slice(0, n - 1).trimEnd() + '…' : s || '');

/** Title plus description when the description adds something. */
export function pageLabel(f, max = 110) {
  const title = f.title || '';
  let d = f.description || '';
  if (d && title && d.toLowerCase().startsWith(title.toLowerCase())) d = d.slice(title.length).replace(/^[\s:—–-]+/, '');
  const label = title && d ? `${title}: ${d}` : title || d;
  return clip(label.replace(/\s+/g, ' '), max);
}

/** `<domain>/_outline.md`: one line per page — path (relative to the domain), label, size. */
export function renderOutline(domain, files) {
  const lines = [
    `# ${domain} — ${files.length} page${files.length === 1 ? '' : 's'}`,
    '',
    '<!-- GENERATED by `docs reindex` from the pages below; do not edit. Format: path — title: description (lines) -->',
    '',
  ];
  for (const f of files) {
    const rel = f.path.startsWith(domain + '/') ? f.path.slice(domain.length + 1) : `../${f.path}`;
    const label = pageLabel(f);
    lines.push(`${rel}${label ? ` — ${label}` : ''} (${f.lines})`);
  }
  return lines.join('\n') + '\n';
}

/**
 * A domain's summary: what its pages are about, in one short line.
 *
 * Few pages: their titles. Otherwise its page groups by path prefix, largest first
 * (`docs/api/admin-graphql (66), docs/apps/build (15), …`): URL paths name the
 * library/product/section in practice, and they cost nothing to derive. A group
 * holding most of the domain is split into its subdirectories (repeatedly), since
 * "docs (120)" says nothing; single-child directory chains are collapsed.
 */
export function summarizeDomain(domain, files, maxLen = 130) {
  if (files.length <= 3) {
    return clip(files.map(f => clip(f.title || f.path.split('/').pop().replace(/\.md$/, ''), 60)).join('; '), maxLen);
  }
  const root = { n: 0, pages: 0, kids: new Map() };
  for (const f of files) {
    const rel = f.path.startsWith(domain + '/') ? f.path.slice(domain.length + 1) : '';
    let node = root;
    node.n++;
    for (const d of rel.split('/').slice(0, -1)) {
      let k = node.kids.get(d);
      if (!k) { k = { n: 0, pages: 0, kids: new Map() }; node.kids.set(d, k); }
      k.n++;
      node = k;
    }
    node.pages++;
  }
  // A group: a directory prefix and its subtree (or `pages` = files directly in it).
  const collapse = (prefix, node) => {
    while (node.pages === 0 && node.kids.size === 1) {
      const [name, kid] = [...node.kids][0];
      prefix += name + '/';
      node = kid;
    }
    return { prefix, node, n: node.n, leafOnly: false };
  };
  const children = g => {
    const out = [...g.node.kids].map(([name, kid]) => collapse(g.prefix + name + '/', kid));
    if (g.node.pages) out.push({ prefix: g.prefix, node: g.node, n: g.node.pages, leafOnly: true });
    return out;
  };
  let groups = children(collapse('', root));
  for (let i = 0; i < 6; i++) {
    groups.sort((a, b) => b.n - a.n);
    const big = groups.find(g => !g.leafOnly && g.node.kids.size > 0 && (g.node.kids.size + (g.node.pages ? 1 : 0)) > 1);
    if (!big || big.n < files.length * 0.4) break;
    groups = groups.filter(g => g !== big).concat(children(big));
  }
  groups.sort((a, b) => b.n - a.n);
  const label = g => (g.leafOnly ? `${g.prefix || './'}*.md (${g.n})` : `${g.prefix.slice(0, -1)} (${g.n})`);
  let out = '';
  for (const g of groups) {
    const next = out ? `${out}, ${label(g)}` : label(g);
    if (next.length > maxLen) { out += ', …'; break; }
    out = next;
  }
  return out;
}

/** `catalog.md`: one line per domain. */
export function renderCatalog(byDomain) {
  const domains = [...byDomain.keys()].sort();
  const total = domains.reduce((n, d) => n + byDomain.get(d).length, 0);
  const lines = [
    `# Documentation cache — ${domains.length} domains, ${total} pages`,
    '',
    '<!-- GENERATED by `docs reindex`; do not edit. -->',
    'Search sections: `node scripts/docs.mjs search "<query>"`. Pages per domain: `<domain>/_outline.md`.',
    'Format: domain (pages): path groups (pages)',
    '',
  ];
  for (const d of domains) {
    const files = byDomain.get(d);
    const summary = summarizeDomain(d, files);
    lines.push(`${d} (${files.length})${summary ? `: ${summary}` : ''}`);
  }
  return lines.join('\n') + '\n';
}

export function groupByDomain(files) {
  const m = new Map();
  for (const f of files) {
    if (!m.has(f.domain)) m.set(f.domain, []);
    m.get(f.domain).push(f);
  }
  for (const list of m.values()) list.sort((a, b) => a.path.localeCompare(b.path));
  return m;
}

/**
 * Rewrite the catalog and the outlines of the given domains (all when null).
 * Outlines of domains that no longer have pages are removed.
 */
export function writeGenerated(rootAbs, files, domains = null) {
  const byDomain = groupByDomain(files);
  const written = [];
  const targets = domains ? [...domains] : [...byDomain.keys()];
  for (const d of targets) {
    const file = join(rootAbs, d, '_outline.md');
    const list = byDomain.get(d);
    if (!list) {
      if (existsSync(file)) { try { unlinkSync(file); written.push(file); } catch { /* raced */ } }
      continue;
    }
    // Root-level v1 pages (`fly.io.md`) have no domain directory; do not create one
    // just for an outline of a single page.
    if (!existsSync(join(rootAbs, d))) continue;
    if (writeAtomic(file, renderOutline(d, list))) written.push(file);
  }
  if (writeAtomic(join(rootAbs, 'catalog.md'), renderCatalog(byDomain))) written.push(join(rootAbs, 'catalog.md'));
  return written;
}
