// The person's grant to the stand-in (spec grant, decision grantCovers): which decision kinds the stand-in may
// decide alone, and until when. Each test drives a real store through runtime.apply(), the way the host does.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { tempDir } from './tmp.js';
import { apply, start, post } from './send.js';
import { openStore, init, ack, status, apply as applyEvent, readDecisionLog, logPrecedents, grantDecisions, pickAudit, openAudits, renderPage, verifyTaps, specs } from '../src/index.js';

const T0 = '2026-10-28T10:00:00.000Z';
const at = (minutes) => new Date(Date.parse(T0) + minutes * 6e4).toISOString();
const hoursAfter = (iso, h) => new Date(Date.parse(iso) + h * 36e5).toISOString();
const person = { actor: { kind: 'person', id: 'sd' } };
const tapOn = (ref) => ({ ...person, source: { kind: 'tap', ref }, relayedBy: 'host' });
const session = (id) => ({ actor: { kind: 'session', id }, source: { kind: 'cli', ref: 'harness send' } });
const bin = new URL('../bin/harness.js', import.meta.url).pathname;
const harness = (dir, ...args) => spawnSync(process.execPath, [bin, ...args, '--dir', dir], { encoding: 'utf8', env: { PATH: process.env.PATH, HOME: process.env.HOME, CLAUDE_CODE_SESSION_ID: 'lead' } });

function fresh() {
  const store = openStore(tempDir('harness-grant-'));
  init(store, {}, T0);
  start(store, T0);
  return store;
}

/** A session asks for the checklist; returns the grant actor's address and its postGrantCard effect. */
function ask(store, now = T0) {
  const r = apply(store, { type: 'GRANT_ASKED' }, { now });
  assert.equal(r.refused, undefined, r.why);
  const effect = store.pending().findLast((e) => e.name === 'postGrantCard');
  assert.ok(effect, 'the ask queues postGrantCard');
  return { address: effect.subject, effect };
}

/** The person's ticks on the checklist at `address`, posted first unless `card` names it. */
function grant(store, address, picks, { now = T0, card } = {}) {
  const ref = card ?? post(store, address, undefined, now);
  return applyEvent(store, { type: 'PERSON_GRANTED', picks, ...tapOn(ref) }, { to: address, now });
}
const until = (h, askedAt = T0) => `until:${hoursAfter(askedAt, h)}`;
const liveGrant = (store) => store.read().snapshot.context.grant;

/** An item at tier `tier` whose plan decision is open and waiting on the stand-in. */
function itemAtPlan(store, id = 'x', tier = 2, now = T0) {
  apply(store, { type: 'REQUEST_RECEIVED', request: { id } }, { now });
  ack(store, store.pending().filter((e) => e.name === 'dispatchRun').map((e) => e.id));
  apply(store, { type: 'RUN_FAILED' }, { to: `item:${id}`, now });
  apply(store, { type: 'TRIAGED', tier, criteria: ['a works'] }, { to: `item:${id}`, now });
  return `item:${id}/decision:${id}:plan:1`;
}
const answer = (store, to, now, { choice = 'approve', confidence = 0.95, reason = 'small and covered' } = {}) =>
  apply(store, { type: 'STAND_IN_ANSWERED', answer: { choice, confidence, ...(reason != null && { reason }) } }, { to, now });
const decision = (store, address) => status(store).items.flatMap((i) => i.decisions).find((d) => d.address === address);
const lastLogged = (store) => (logPrecedents(store), readDecisionLog(store).at(-1));

/** Build, check and pass CI on an item whose plan was approved, so its accept decision opens (decision 2). */
function toAccept(store, id, now) {
  apply(store, { type: 'RUN_SUCCEEDED' }, { to: `item:${id}`, now });
  apply(store, { type: 'CRITERION_CHECKED', criterion: 'a works', verdict: 'met', evidence: 'test a' }, { to: `item:${id}`, now });
  apply(store, { type: 'CHECKS_PASSED' }, { to: `item:${id}`, now });
  return `item:${id}/decision:${id}:accept:2`;
}

test('every decision says its door, from the spec: plan and accept are two-way, merge one-way', () => {
  const classes = specs.decision.meta.classes;
  assert.deepEqual(Object.fromEntries(Object.entries(classes).map(([k, c]) => [k, c.door])), { plan: 'two-way', accept: 'two-way', merge: 'one-way' });
  assert.equal(specs.decision.context.door, 'one-way', 'a class the spec does not list is a one-way door');
  const store = fresh();
  const plan = itemAtPlan(store);
  assert.equal(decision(store, plan).door, 'two-way');
});

test('the checklist card is generated by the machine: every decision kind, the one-way-door box and end times', () => {
  const store = fresh();
  const { address, effect } = ask(store, at(5));
  assert.equal(address, 'grant:1');
  const kinds = Object.keys(specs.decision.meta.classes).map((k) => `kind:${k}`);
  const ends = specs.grant.meta.checklist.endsAfterHours.map((h) => until(h, at(5)));
  assert.deepEqual(effect.detail.options, [...kinds, 'one-way', ...ends]);
  // harness card prints the checklist for the host: one tick per option, and the tap that answers it.
  const card = JSON.parse(harness(store.dir, 'card', effect.id).stdout);
  assert.equal(card.address, 'grant:1');
  assert.deepEqual(card.checks.map((c) => c.id), effect.detail.options);
  assert.match(card.checks.find((c) => c.id === 'kind:merge').label, /one-way/);
  assert.match(card.tap, /PERSON_GRANTED/);
  // A person, a tap or an agent cannot ask; a session can, and asking grants nothing.
  assert.equal(applyEvent(store, { type: 'GRANT_ASKED', ...tapOn('cmsg_x') }, { now: T0 }).refused, true);
  assert.equal(liveGrant(store), null);
});

test('only the person\'s tap on the checklist the machine asked for records a grant', () => {
  const store = fresh();
  const { address } = ask(store);
  const picks = ['kind:plan', until(8)];
  const before = () => [store.read().version, store.events().length];
  // Before the card is posted, a tap names no card the machine knows.
  let v = before();
  assert.equal(applyEvent(store, { type: 'PERSON_GRANTED', picks, ...tapOn('cmsg_early') }, { to: address, now: T0 }).refused, true);
  assert.deepEqual(before(), v, 'a refusal writes nothing');
  const card = post(store, address, 'cmsg_checklist');
  // Not from a session, an agent or a person without a tap; not from a tap on another card.
  for (const by of [session('lead'), { actor: { kind: 'agent', id: 'lead/a1' }, source: { kind: 'cli', ref: 'x' } }, { ...person, source: { kind: 'cli', ref: card } }, tapOn('cmsg_other')]) {
    v = before();
    assert.equal(applyEvent(store, { type: 'PERSON_GRANTED', picks, ...by }, { to: address, now: T0 }).refused, true, JSON.stringify(by));
    assert.deepEqual(before(), v);
  }
  // GRANT_GIVEN is the grant actor's own report: from outside it is refused, whoever sends it.
  for (const by of [session('lead'), tapOn(card)])
    assert.equal(applyEvent(store, { type: 'GRANT_GIVEN', grant: { kinds: ['merge'], oneWay: true, until: '2099-01-01T00:00:00Z' }, ...by }, { now: T0 }).refused, true);
  // Picks must be the card's own options, each once, with exactly one end time.
  for (const bad of [['kind:deploy', until(8)], ['kind:plan'], ['kind:plan', until(8), until(24)], ['kind:plan', 'kind:plan', until(8)], ['kind:plan', 'until:2099-01-01T00:00:00.000Z'], 'kind:plan', [['kind:plan'], until(8)]])
    assert.equal(applyEvent(store, { type: 'PERSON_GRANTED', picks: bad, ...tapOn(card) }, { to: address, now: T0 }).refused, true, JSON.stringify(bad));
  assert.equal(liveGrant(store), null, 'nothing refused made a grant');
  const r = grant(store, address, picks, { card });
  assert.equal(r.refused, undefined, r.why);
  assert.deepEqual(liveGrant(store), { card, kinds: ['plan'], oneWay: false, until: hoursAfter(T0, 8), at: T0 });
  // The checklist is answered: a second tap on it changes nothing, so it cannot widen or extend the grant.
  assert.throws(() => applyEvent(store, { type: 'PERSON_GRANTED', picks: ['kind:plan', 'kind:merge', 'one-way', until(72)], ...tapOn(card) }, { to: address, now: at(1) }), /no actor|refused/);
  assert.deepEqual(liveGrant(store).kinds, ['plan']);
  // The tap is on the log for verify-taps, with the picks it claims.
  const row = verifyTaps(store).find((t) => t.type === 'PERSON_GRANTED');
  assert.deepEqual([row.card, row.choice], [card, picks]);
});

test('a new ask withdraws the unanswered checklist, so its card can no longer grant', () => {
  const store = fresh();
  const first = ask(store);
  const card = post(store, first.address, 'cmsg_first');
  const second = ask(store, at(1));
  assert.equal(second.address, 'grant:2');
  assert.throws(() => applyEvent(store, { type: 'PERSON_GRANTED', picks: ['kind:plan', until(8)], ...tapOn(card) }, { to: first.address, now: at(2) }), /no actor/);
  assert.equal(applyEvent(store, { type: 'PERSON_GRANTED', picks: ['kind:plan', until(8, at(1))], ...tapOn(card) }, { to: second.address, now: at(2) }).refused, true, 'the first card does not answer the second');
  assert.equal(liveGrant(store), null);
});

test('under a live grant the stand-in decides a two-way door it names, on a fresh ladder and at tier 2', () => {
  const store = fresh();
  const { address } = ask(store);
  grant(store, address, ['kind:plan', 'kind:accept', until(8)]);
  const plan = itemAtPlan(store, 'x', 2, at(1));
  assert.equal(decision(store, plan).autonomy, 'recommend', 'the ladder alone would send it to the person');
  answer(store, plan, at(2));
  assert.equal(status(store).items[0].state, 'active.building', 'the stand-in approved the plan alone');
  const row = lastLogged(store);
  assert.deepEqual([row.decidedBy, row.authority, row.door, row.grant?.card, row.standIn.reason], ['stand-in', 'grant', 'two-way', liveGrant(store).card, 'small and covered']);
  // Accept is two-way too, and the grant names it: with every criterion met the stand-in accepts.
  const accept = toAccept(store, 'x', at(3));
  answer(store, accept, at(4));
  // Merge is a one-way door the grant does not name: the person decides.
  const merge = 'item:x/decision:x:merge:3';
  assert.equal(decision(store, merge)?.state, 'askingStandIn');
  answer(store, merge, at(5));
  assert.deepEqual([decision(store, merge).door, decision(store, merge).state], ['one-way', 'awaitingPerson']);
});

test('a grant decides nothing outside its kinds, without a reason, below the threshold, or on an unmet accept', () => {
  const store = fresh();
  grant(store, ask(store).address, ['kind:accept', until(8)]);
  const plan = itemAtPlan(store, 'p', 2, at(1));
  answer(store, plan, at(2));
  assert.equal(decision(store, plan).state, 'awaitingPerson', 'plan is not in the grant');
  for (const [id, a] of [['q', { reason: null }], ['r', { confidence: 0.5 }]]) {
    const store2 = fresh();
    grant(store2, ask(store2).address, ['kind:plan', until(8)]);
    const d = itemAtPlan(store2, id, 1, at(1));
    answer(store2, d, at(2), a);
    assert.equal(decision(store2, d).state, 'awaitingPerson', JSON.stringify(a));
  }
  // An accept whose criteria are not all met goes to the person under a grant too.
  const s3 = fresh();
  grant(s3, ask(s3).address, ['kind:plan', 'kind:accept', until(8)]);
  answer(s3, itemAtPlan(s3, 'u', 2, at(1)), at(2));
  apply(s3, { type: 'RUN_SUCCEEDED' }, { to: 'item:u', now: at(3) });
  apply(s3, { type: 'CHECKS_PASSED' }, { to: 'item:u', now: at(3) });
  answer(s3, 'item:u/decision:u:accept:2', at(4));
  assert.equal(decision(s3, 'item:u/decision:u:accept:2').state, 'awaitingPerson');
});

test('a one-way door is decided only under a grant that names it and ticks the one-way-door box', () => {
  for (const [picks, expected] of [
    [['kind:plan', 'kind:accept', 'kind:merge', until(8)], 'awaitingPerson'],
    [['kind:plan', 'kind:accept', 'one-way', until(8)], 'awaitingPerson'],
    [['kind:plan', 'kind:accept', 'kind:merge', 'one-way', until(8)], 'merging']
  ]) {
    const store = fresh();
    grant(store, ask(store).address, picks);
    answer(store, itemAtPlan(store, 'm', 2, at(1)), at(2));
    answer(store, toAccept(store, 'm', at(3)), at(4));
    answer(store, 'item:m/decision:m:merge:3', at(5));
    const item = status(store).items[0];
    const got = item.state === 'active.merging' ? 'merging' : item.decisions.find((d) => d.decisionClass === 'merge')?.state;
    assert.equal(got, expected, JSON.stringify(picks));
  }
});

test('a grant ends at its end time, and a new tap replaces it', () => {
  const store = fresh();
  grant(store, ask(store).address, ['kind:plan', until(2)]);
  // At the end time and after, the grant decides nothing: the person does.
  const late = itemAtPlan(store, 'late', 2, hoursAfter(T0, 2));
  answer(store, late, hoursAfter(T0, 2));
  assert.equal(decision(store, late).state, 'awaitingPerson');

  const s2 = fresh();
  grant(s2, ask(s2).address, ['kind:plan', 'kind:accept', until(72)]);
  // The person taps a new checklist with less in it: the old grant is gone, the new one alone decides.
  const next = ask(s2, at(1));
  grant(s2, next.address, ['kind:accept', until(8, at(1))], { now: at(2) });
  assert.deepEqual(liveGrant(s2).kinds, ['accept']);
  const plan = itemAtPlan(s2, 'n', 2, at(3));
  answer(s2, plan, at(4));
  assert.equal(decision(s2, plan).state, 'awaitingPerson', 'the replaced grant named plan; it decides nothing');
  // A checklist with no kind ticked ends the grant.
  const off = ask(s2, at(5));
  grant(s2, off.address, [until(2, at(5))], { now: at(6) });
  assert.deepEqual(liveGrant(s2).kinds, []);
});

test('every grant decision is listed for the person, with its reason, on mission control and in the daily audit', () => {
  const store = fresh();
  grant(store, ask(store).address, ['kind:plan', until(24)]);
  for (const [i, id] of ['a', 'b', 'c', 'd', 'e'].entries()) answer(store, itemAtPlan(store, id, 2, at(i + 1)), at(i + 1), { reason: `reason for ${id}` });
  logPrecedents(store);
  const granted = grantDecisions(readDecisionLog(store));
  assert.deepEqual(granted.map((r) => r.item), ['a', 'b', 'c', 'd', 'e']);
  const page = renderPage(status(store), { granted });
  assert.match(page, /Decided under your grant/);
  for (const id of ['a', 'b', 'c', 'd', 'e']) assert.match(page, new RegExp(`reason for ${id}`));
  // The audit picks up to 3 to reverse, grant decisions first, and its card lists every grant decision.
  const audit = pickAudit(store, { by: session('lead'), now: hoursAfter(T0, 1) });
  assert.equal(audit.picks.length, 3);
  assert.deepEqual(audit.granted.map((r) => r.item), ['a', 'b', 'c', 'd', 'e']);
  const [open] = openAudits(store);
  for (const id of ['a', 'b', 'c', 'd', 'e']) assert.match(open.ask.context, new RegExp(`${id} plan: approve`));
  assert.match(open.ask.context, /reason for e/);
});
